    # Test: har kategoriya uchun nechta noyob variant borligini ko'rsatish
    combos = total_combinations()
    total = 0
    for mood, count in combos.items():
        print(f"{mood}: {count} ta noyob variant")
        total += count
    print(f"\nJAMI: {total} ta noyob motivatsion xabar!")
