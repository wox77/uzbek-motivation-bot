def generate_quote(mood: str) -> str:
    """
    Berilgan kayfiyat uchun tasodifiy, noyob motivatsion xabar yaratadi.
    Har chaqiruvda 3 qismni tasodifiy birlashtirib, minglab
    noyob kombinatsiya hosil qiladi (AI yoki internet kerak emas).
    """
    parts = QUOTE_PARTS.get(mood)
    if not parts:
        # fallback umumiy mood
        parts = QUOTE_PARTS["kelajak"]

    opener = random.choice(parts["openers"])
    core = random.choice(parts["cores"])
    closer = random.choice(parts["closers"])

    return f"{opener}\n\n{core}\n\n{closer}"


def total_combinations():
    """Har bir kategoriya uchun mumkin bo'lgan noyob kombinatsiyalar sonini hisoblaydi."""
    result = {}
    for mood, parts in QUOTE_PARTS.items():
        count = len(parts["openers"]) * len(parts["cores"]) * len(parts["closers"])
        result[mood] = count
    return result


